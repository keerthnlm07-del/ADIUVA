import 'package:equatable/equatable.dart';

/// Entity representing an Indian Sign Language (ISL) Video Clip
class IslVideoClip extends Equatable {
  final String category;
  final String displayText;
  final String realFilename;
  final String assetPath;
  final String datasetPath;
  final int totalDatasetClips;
  final List<String> aliases;
  final String tag;

  const IslVideoClip({
    required this.category,
    required this.displayText,
    required this.realFilename,
    required this.assetPath,
    required this.datasetPath,
    required this.totalDatasetClips,
    required this.aliases,
    required this.tag,
  });

  @override
  List<Object?> get props => [category, realFilename, assetPath];
}

