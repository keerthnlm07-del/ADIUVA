  static String normalize(String text) {
    return text
        .toLowerCase()
        .trim()
        .replaceAll(RegExp(r"""[!?,.:;'"()\-]"""), '')
        .replaceAll(RegExp(r'\s+'), ' ');
  }

  /// Match spoken or typed query to a real demonstration video clip
  static IslVideoClip? findClip(String query) {
    final clean = normalize(query);
    if (clean.isEmpty) return null;

    // 1. Exact alias or category match
    for (final clip in clips) {
      if (clip.aliases.contains(clean) || normalize(clip.category) == clean) {
        return clip;
      }
    }

    // 2. Substring match
    for (final clip in clips) {
      for (final alias in clip.aliases) {
        if (clean.contains(alias) || alias.contains(clean)) {
          return clip;
        }
      }
    }

    return null;
  }
